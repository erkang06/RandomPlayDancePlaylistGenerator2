    private boolean checkIfAudioFile(File file) {
        try {
            String mimeType = Files.probeContentType(file.toPath());
            if (mimeType.startsWith("audio/")) {
                return true;
            }
        } catch (Exception e) {
            showErrorDialog(e.getLocalizedMessage());
        }
        return false;
    }
    
