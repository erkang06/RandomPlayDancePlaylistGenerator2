    private void tblPlaylistKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_tblPlaylistKeyPressed
        int keyCode = evt.getKeyCode();
        evt.consume();
        switch (keyCode) {
            case java.awt.event.KeyEvent.VK_UP:
                movePlaylistSong(false);
                break;
            case java.awt.event.KeyEvent.VK_DOWN:
                movePlaylistSong(true);
                break;
        }
    }//GEN-LAST:event_tblPlaylistKeyPressed
    
    private boolean isPlaylistEmpty() {
        if (tblPlaylist.getRowCount() == 0) {
            showErrorDialog("Playlist is empty");
            return true;
        } return false;
    }
    
    private boolean isPathValid() {
        String filepath = tfLocation.getText();
        if (!filepath.equals("")) {
            try {
                Paths.get(filepath);
                return true;
            } catch (InvalidPathException | NullPointerException ex) {} 
        } 
        showErrorDialog("Export path isn't valid");
        return false;
    }
    
    private boolean doesOutputFileNameExist() {
        if (tfFileName.getText().isEmpty()) {
            showErrorDialog("No output file name");
            return false;
        } return true;
    }
    
    private String getEncoder() {
        String encoder = switch (cbFileFormat.getSelectedItem().toString()) {
            case ".mp3" -> "libmp3lame";
            case ".wav" -> "pcm_s16le";
            case ".m4a" -> "aac";
            case ".ogg" -> "libvorbis";
            case ".flac" -> "flac";
            default -> "libmp3lame"; // not selecting should default to mp3
        };
        return encoder;
    }
    
    private String getFileName() {
        String fileName = tfFileName.getText();
        if (!fileName.equals("")) {
            return fileName;
        } return "output";
    }
    
    private String getFileFormat() {
        String fileFormat = cbFileFormat.getSelectedItem().toString();
        // not selecting should default to mp3
        if (fileFormat == "File Format") {
            fileFormat = ".mp3";
        }
        return fileFormat;
    }
    
